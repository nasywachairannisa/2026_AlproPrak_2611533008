# Nilai yang dimasukan akan dikonversi menjadi tipe data integer
# Program operator perbandingan dalam python

angka1_3008 = int(input("input angka-1: "))
angka2_3008 = int(input("input angka-2:"))

# Lebih besar dari
hasil_3008 = angka1_3008 > angka2_3008
print("\nOperator lebih besar dari")
print("angka1_3008 > angka2_3008 =", hasil_3008)

# Lebih kecil dari
hasil_3008 = angka1_3008 < angka2_3008
print("\nOperator lebih kecil dari")
print("angka1_3008 < angka2_3008 =", hasil_3008)

# Lebih besar dari atau sama dengan
hasil_3008 = angka1_3008 >= angka2_3008
print("\nOperator lebih besar dari atau sama dengan")
print("angka1_3008 >= angka2_3008 =", hasil_3008)

# Lebih kecil dari atau sama dengan
hasil_3008 = angka1_3008 <= angka2_3008
print("\nOperator lebih kecil dari atau sama dengan")
print("angka1_3008 <= angka2_3008 =", hasil_3008)

# Sama dengan
hasil_3008 = angka1_3008 == angka2_3008
print("\nOperator sama dengan")
print("angka1_3008 == angka2_3008 =", hasil_3008)

# Tidak sama dengan
hasil_3008 = angka1_3008 != angka2_3008
print("\nOperator tidak sama dengan")
print("angka1_3008 != angka2_3008 =", hasil_3008)

